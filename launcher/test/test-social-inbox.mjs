import assert from 'node:assert/strict';
import { consumeInbox, appendNotification, markNotificationsRead } from '../src/core/social-inbox.js';
const a = { at: 0, seen: [] }, b = { at: 0, seen: [] };
const message = { id: 'm1', at: 100, kind: 'msg', from: 'friend' };
assert.equal(consumeInbox(a, { now: 100, items: [message, message] }).length, 1);
assert.equal(consumeInbox(a, { now: 101, items: [message] }).length, 0);
assert.equal(consumeInbox(b, { now: 101, items: [message] }).length, 1, 'accounts remain independent');
const restored = JSON.parse(JSON.stringify(a));
assert.equal(consumeInbox(restored, { now: 102, items: [message, { ...message, id: 'm2' }] }).length, 1);
assert.equal(restored.at, 102);
const rows = [];
assert.equal(appendNotification(rows, message), true);
assert.equal(appendNotification(rows, message), false);
appendNotification(rows, { id: 'app', kind: 'app', from: 'friend' }, 200);
markNotificationsRead(rows, { from: 'friend' });
assert.equal(rows.find((n) => n.id === 'm1').read, true);
assert.equal(rows.find((n) => n.id === 'app').read, false);
markNotificationsRead(rows);
assert.ok(rows.every((n) => n.read));
for (let i = 0; i < 400; i++) appendNotification(rows, { id: `n${i}`, kind: 'app' }, i);
assert.equal(rows.length, 150);
assert.equal(rows[0].id, 'n399');
consumeInbox(a, { items: Array.from({ length: 400 }, (_, i) => ({ id: `m${i}` })) });
assert.equal(a.seen.length, 300);
console.log('✅ Réception et notifications : doublons, reprise, isolation des comptes, lecture et limites');
