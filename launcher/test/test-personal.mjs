import assert from 'node:assert/strict';
import { cleanHome, cleanNotebook, mergeNotebooks, cachedTask } from '../src/core/personal.js';
import { pickBackup, mergeBackup } from '../src/core/backup.js';
const home = cleanHome({ order:['free','free','bogus'], hidden:['hero','bad'], pins:['a','a','__proto__'],actions:[] });
assert.equal(home.order[0], 'free'); assert.equal(home.order.length,10); assert.deepEqual(home.hidden,['hero']); assert.deepEqual(home.pins,['a']); assert.deepEqual(home.actions,[]);
assert.equal(cleanHome({pins:Array.from({length:20},(_,i)=>String(i))}).pins.length,12);
assert.throws(()=>cleanNotebook({links:'javascript:alert(1)'})); assert.throws(()=>cleanNotebook({links:'https://user:pw@example.com'}));
assert.equal(cleanNotebook({notes:'x'.repeat(11000)}).notes.length,10000);
const old = cleanNotebook({notes:'ancien'},1), recent = cleanNotebook({notes:'récent',links:'https://example.com'},2);
assert.equal(mergeNotebooks({a:recent},{a:old}).a.notes,'récent');
assert.equal(mergeNotebooks({a:old},{a:recent}).a.notes,'récent');
assert.equal(mergeNotebooks({a:recent},{a:{...old,updatedAt:Date.now()+999999}}).a.notes,'récent');
const backup=pickBackup({notebooks:{a:recent},settings:{home}}); assert.equal(mergeBackup({},backup).notebooks.a.notes,'récent');
let now=1, calls=0, release;
const read=cachedTask(()=>{calls++; return new Promise(r=>{release=r;});},10,()=>now);
const a=read(),b=read(); assert.equal(a,b); await Promise.resolve(); release(42); assert.equal(await a,42); assert.equal(await read(),42); assert.equal(calls,1);
now=12; const c=read(); await Promise.resolve(); release(43); assert.equal(await c,43); assert.equal(calls,2);
let tries=0;const retry=cachedTask(()=>{if(!tries++) throw new Error('offline');return 7;},100); await assert.rejects(retry);assert.equal(await retry(),7);
console.log('✓ Accueil, validation des carnets, fusion cloud, cache concurrent et reprise après erreur');
